// Run with Node.js after editing web assets. No npm dependencies required.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const root = __dirname;
const assets = [
  ['rostros_html', 'rostros.html'],
  ['rostros_js', 'rostros.js'],
  ['rostros_css', 'rostros.css'],
  ['bootstrap_css', 'vendor/bootstrap.min.css'],
  ['sweetalert_js', 'vendor/sweetalert2.min.js'],
  ['sweetalert_css', 'vendor/sweetalert2.min.css'],
];
let out = '// Generated by custompage/build-web.cjs. Edit custompage/ sources instead.\n#pragma once\n#include <stdint.h>\n';
for (const [name, file] of assets) {
  const bytes = zlib.gzipSync(fs.readFileSync(path.join(root, file)), {level: 9});
  out += `static const uint8_t ${name}_gz[] = {\n`;
  for (let i = 0; i < bytes.length; i += 24) out += [...bytes.subarray(i, i + 24)].join(',') + ',\n';
  out += '};\n';
  console.log(`${file}: ${bytes.length} bytes gzip`);
}
fs.writeFileSync(path.join(root, 'rostros_assets.h'), out);
// Preserve the official page's controls and add only a navigation link.
const stock = fs.readFileSync(path.join(root, '..', 'camera_index.h'), 'utf8');
let linked = '// Generated from camera_index.h; original controls preserved.\n#pragma once\n#include <stdint.h>\n';
let count = 0;
for (const match of stock.matchAll(/const uint8_t (index_\w+_html_gz)\[\] = \{([\s\S]*?)\};/g)) {
  const original = Buffer.from(match[2].match(/0x[0-9a-f]+/gi).map(value => Number(value)));
  const html = zlib.gunzipSync(original).toString('utf8');
  const updated = html.replace(/<body[^>]*>/i, body => body + '<p><a href="/rostros">Administrar rostros: nombres y fotos</a></p>');
  if (updated === html) throw new Error('Original HTML body not found');
  const bytes = zlib.gzipSync(updated, {level:9});
  linked += `#define ${match[1]}_len ${bytes.length}\nstatic const uint8_t ${match[1]}[] = {\n`;
  for (let i=0; i<bytes.length; i+=24) linked += [...bytes.subarray(i,i+24)].join(',') + ',\n';
  linked += '};\n'; count++;
}
if (count !== 3) throw new Error('Expected all three original sensor pages');
fs.writeFileSync(path.join(root, 'stock_index_assets.h'), linked);
